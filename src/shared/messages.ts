const MESSAGES: Record<InterfaceLanguage, Record<MessageKey, string>> = { fr: french, en: english }

export function translate(language: InterfaceLanguage, key: MessageKey, values: Record<string, string> = {}): string {
  return MESSAGES[language][key].replace(/\{(\w+)\}/g, (placeholder, name: string) => values[name] ?? placeholder)
}

export function isMessageKey(value: string): value is MessageKey {
  return value in french
}
